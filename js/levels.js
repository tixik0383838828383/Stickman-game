/* levels.js — 12 встроенных уровней. Формат = JSON, который понимает редактор (экспорт/импорт).
   Координаты в «мировых» пикселях, ось Y вниз. start — точка под ногами игрока.
   t: plat | spike | saw | sblock | spinner | dart | laser | plate | coin | cp | fin | rope | crate | secret | deco | txt
   Необязательное поле route — путевые точки для автотеста-бота (tests/bot.js). */
'use strict';
const LEVELS = [];

/** Мини-конструктор уровней: каждая функция добавляет объект в список */
function LB() {
  const o = [];
  const api = {
    o,
    add(d) { o.push(d); return api; },
    ground(x, w, y, h, k, ex) { return api.add(Object.assign({ t: 'plat', x, y: y === undefined ? 700 : y, w, h: h || 260, k: k || 'solid' }, ex || {})); },
    plat(x, y, w, h, k, ex) { return api.add(Object.assign({ t: 'plat', x, y, w, h: h || 24, k: k || 'solid' }, ex || {})); },
    coin(x, y, v) { return api.add({ t: 'coin', x, y, v: v || 1 }); },
    coins(x, y, n, gap, dy) { for (let i = 0; i < n; i++) api.coin(x + i * gap, y + (dy || 0) * i); return api; },
    spike(x, y, n, dir, ex) { return api.add(Object.assign({ t: 'spike', x, y, n, dir: dir || 'u' }, ex || {})); },
    saw(x, y, r, p, ex) { return api.add(Object.assign({ t: 'saw', x, y, r, p: p || { ty: 'static' } }, ex || {})); },
    cp(x, y) { return api.add({ t: 'cp', x, y }); },
    fin(x, y) { return api.add({ t: 'fin', x, y }); },
    txt(x, y, s, sz, ex) { return api.add(Object.assign({ t: 'txt', x, y, s, sz: sz || 26 }, ex || {})); },
    deco(x, y, k, sz, ex) { return api.add(Object.assign({ t: 'deco', x, y, k, sz: sz || 40 }, ex || {})); },
    rope(x, y, h) { return api.add({ t: 'rope', x, y, h }); },
    crate(x, y) { return api.add({ t: 'crate', x, y }); },
    secret(x, y, w, h) { return api.add({ t: 'secret', x, y, w, h }); },
  };
  return api;
}
const mk = (name, world, hint, w, h, sx, sy, b, extra) => LEVELS.push(Object.assign({ name, world, hint, w, h, start: { x: sx, y: sy }, obj: b.o }, extra || {}));

